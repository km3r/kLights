"""
The event's look library: looks.json, generated by the porter, and
parametric_looks.json, the block looks made in Studio. Read at start, watched
on disk, and edited from Studio's Looks page through `lookstore`.

Every edit is an edit to parametric_looks.json: written on the worker,
quoting the rev the editor read, and then the whole library is read again
there and installed here -- so what the picker lists, what is on stage and
what the show folder's programs were built from are never two different
libraries.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path
from typing import Any, Callable, Optional

from .. import blocks as blocksmod
from .. import config as configmod
from .. import library as libmod
from .. import lookstore
from .. import params as parammod
from .. import showfiles
from .. import showlibrary
from ..commands import CONFIGURE, command
from .common import S, _BASE_REV, _NAME
from .picture import default_setlist
from .presets import save_presets


class Looks:
    """The look library, and Studio's edits to it."""

    def _init_library(self) -> None:
        # The ported library if the event has one, otherwise a small scaffold.
        # Falling back rather than failing means a brand-new event runs before
        # anything has been ported into it.
        #
        # Two files, either of them optional (`library.load_library`):
        # looks.json is generated by the porter and guarded as a reproducible
        # artifact, so looks made here cannot live in it and go in
        # `parametric_looks.json` -- which is all an event that was never
        # ported has. Its rev is read BEFORE the library: if the file changes
        # in between, the library reads as out of date and an edit is refused,
        # rather than made against a file nobody loaded.
        looks_seen = lookstore.signature(self.event_dir)
        self.looks_rev = lookstore.file_rev(self.event_dir)
        self.library = libmod.load_library(self.event_dir)
        # Why the look files on disk are not the library that is running, when
        # they changed and would not load. None while they agree.
        self.looks_problem: Optional[str] = None
        # The look files are watched like the show folder is: an edit by hand,
        # or by the MCP server, is read without a restart -- and one that does
        # not load is said, while the library that was running runs on.
        self.look_watcher = showlibrary.Watcher(
            self.event_dir, on_change=self.reload_looks,
            report=lambda text: self.submit_call(lambda: self.note(text)),
            scan=lookstore.signature, what="look file", seen=looks_seen)
        self.setlist = (libmod.setlist_for(self.library) if self.library
                        else default_setlist())
        self.by_name = {e.name: e for e in self.library}
        # Bumped each time a library is installed, after it is: what tells
        # the broadcast thread to send every console the new list
        # (`looks_frame`), which the snapshot does not carry.
        self.library_rev = 0

    def looks_public(self) -> dict:
        """The look library, for `GET /api/looks`: every look with what it is
        and everything that names it.

        Built on the caller's thread (an HTTP one), from references the output
        thread only ever REBINDS -- the library, the presets, the cue list --
        so it reads one whole library or the next, never half of each.
        """
        entries, setlist = self.library, self.setlist
        folder = (self.show_library.folder if self.show_library is not None
                  else None)
        use = lookstore.usage(self.cues.cues if self.cues else (),
                              self.presets, folder, entries)
        manual = {look.name: look.manual_only for look in setlist.looks}
        return {
            "event": self.rig.name, "file": lookstore.FILE,
            # What a save must quote: the file this library was READ from.
            "rev": self.looks_rev,
            # The file has changed since (an edit by hand, MCP) and the engine
            # has not read it yet -- it watches, so that is a second or two --
            # or it would not load, and `problem` says why. Until they agree a
            # save is refused: it would be made against a file nobody loaded.
            # (`problem` alone makes it stale: looks.json can be the file
            # that does not load, with this one untouched.)
            "stale": (self.looks_problem is not None
                      or lookstore.file_rev(self.event_dir) != self.looks_rev),
            "problem": self.looks_problem,
            "groups": list(self.rig.tags()),
            "looks": [lookstore.describe(e, manual.get(e.name, False),
                                         use.get(e.name)) for e in entries],
        }

    @staticmethod
    def _read_looks(event_dir: Path) -> tuple[list, Optional[str], tuple]:
        """The library as the files are now: (entries, the rev a save must
        quote, what the watcher will see). On the worker. The signature and
        the rev are read BEFORE the library: a file that changes in between
        then reads as out of date, and is read again, rather than passing for
        the one that was loaded."""
        seen = lookstore.signature(event_dir)
        rev = lookstore.file_rev(event_dir)
        return libmod.load_library(event_dir), rev, seen

    def _look_edit(self, label: str, work: Callable[[], Any], said: str, *,
                   renamed: Optional[tuple[str, str]] = None,
                   data: Optional[dict] = None) -> object:
        """One edit to the look library: `work` writes the file on the worker
        (what it returns, if anything, rides back in the reply), the library
        is read again there, and installed here."""
        event_dir = self.event_dir

        def job():
            info = work()
            return self._read_looks(event_dir), info if isinstance(info, dict) else {}

        def then(result, respond):
            loaded, info = result
            try:
                moved = self._install_looks(*loaded, renamed=renamed)
            except Exception as exc:                        # noqa: BLE001
                # The file is written and the library is not installed. Said
                # to whoever asked, rather than leaving them to time out; the
                # watcher sees the file is not the library that is running
                # and reads it again by itself.
                self.note(f"{label} wrote the file, but the engine could not "
                          f"take it up: {exc}")
                respond(False, error=f"{lookstore.FILE} was written, but the "
                                     f"engine could not take it up ({exc}). It "
                                     f"reads the file again by itself; check "
                                     f"the look, then the notices")
                return
            respond(True, {"rev": loaded[1] or "", **(data or {}), **info,
                           "cues": max(info.get("cues", 0), moved["cues"]),
                           "presets": moved["presets"]})
            self.note(said)
            if info.get("written"):
                # The show folder was rewritten with the rename: read now,
                # rather than when its own watcher gets round to it.
                self.reload_library()

        return self._on_worker(label, job, then)

    def reload_looks(self) -> None:
        """The look files changed on disk: read them, and make them the
        library. Called on the watcher's thread, so the read goes to the
        worker and the install to the output thread -- and a file that does
        not load changes nothing but what `/api/looks` says about it."""
        event_dir = self.event_dir

        def job():
            try:
                return self._read_looks(event_dir)
            except Exception as exc:                        # noqa: BLE001
                return exc

        def done(result) -> None:
            if isinstance(result, Exception):
                self.looks_problem = str(result)
                # The first thing wrong, in a line: the whole of it is on the
                # Looks page, and a notice is read at a glance.
                first = (result.problems[0] if isinstance(result, configmod.ConfigError)
                         and result.problems else str(result)).strip().splitlines()[0]
                self.note("the look files changed on disk and do not load, so "
                          "the library that was running runs on: " + first)
                return
            self._install_looks(*result)
            self.note("looks read again: the files changed on disk")

        self.worker.submit(job, done, label="reading the looks again")

    def _show_folder_now(self) -> Callable[[], Optional["showfiles.Folder"]]:
        """The show folder as it is on disk when the worker gets to it, for an
        edit that must know what names a look (see `_on_disk`). None without a
        show folder."""
        library = self.show_library
        if library is None:
            return lambda: None
        root, folder = library.root, library.folder
        return lambda: self._on_disk(root, folder)

    @command("look_save", tier=CONFIGURE, args={
        "look": S(dict, required=True),
        "was": S(str, fix="the look's name as you opened it"),
        "hides": S(dict, of={"look": S(str, required=True), "note": S(str)}),
        "base_rev": _BASE_REV})
    def _cmd_look_save(self, m: dict, now: float) -> object:
        """Write one block look: a new one (`was` absent), or a change to the
        one called `was` -- which renames it when `look.name` differs.

        A rename takes everything that names the look with it
        (`lookstore.rename`): the show folder's routines, timelines and
        template sets and cues.json, written on the worker; and here, on the
        output thread, the presets, the running cue list, and whatever is
        tuned or on stage under the old name. The look is written under both
        names until every reference has moved, so a rename stopped part-way
        leaves nothing naming a look that is gone.
        """
        look = lookstore.clean_look(m["look"])
        was, base = m.get("was"), m["base_rev"]
        # A NEW look may hide another as it is made -- a stored look remade
        # as a block look -- in the same write (`lookstore.save`).
        hides = m.get("hides")
        if hides is not None and was is not None:
            raise ValueError("hides is {look, note?}, on a new look only: the "
                             "look the new one takes the place of on the picker")
        name = look["name"]
        renamed = (was, name) if was is not None and was != name else None
        event_dir = self.event_dir
        show_root = self.show_library.root if self.show_library is not None else None
        folder_now = self._show_folder_now()

        def work():
            if renamed is None:
                lookstore.save(event_dir, look, was, base, hides=hides)
                return None
            folder = folder_now()
            return lookstore.rename(
                event_dir, look, was, base,
                show=(show_root, folder) if folder is not None else None)

        warnings = lookstore.group_warnings(look, self.rig)
        said = (f"renamed look {was!r} to {name!r}" if renamed
                else f"saved look {name!r}")
        return self._look_edit(f"saving look {name}", work, said, renamed=renamed,
                               data={"name": name, "warnings": warnings,
                                     "written": []})

    @command("look_delete", tier=CONFIGURE, args={"look": _NAME, "base_rev": _BASE_REV})
    def _cmd_look_delete(self, m: dict, now: float) -> object:
        """Delete a block look nothing names. One a cue, a preset, a routine or
        a timeline still names is refused with where, so a delete can never
        leave a show asking for a look that is gone. A stored look cannot be
        deleted at all -- looks.json is generated -- only hidden."""
        name, base = m["look"], m["base_rev"]
        event_dir, entries = self.event_dir, self.library
        cues = tuple(self.cues.cues) if self.cues else ()
        presets, folder_now = self.presets, self._show_folder_now()
        entry = self.by_name.get(name)

        def work():
            refusal = lookstore.delete_refusal(entry, lookstore.usage(
                cues, presets, folder_now(), entries).get(name))
            if refusal is not None:
                raise ValueError(refusal)
            lookstore.delete(event_dir, name, base)

        return self._look_edit(f"deleting look {name}", work,
                               f"deleted look {name!r}", data={"deleted": name})

    @command("look_hide", tier=CONFIGURE, args={
        "look": _NAME,
        "hidden": S(bool),
        "replaced_by": S(str, fix="a look's name"),
        "note": S(str),
        "base_rev": _BASE_REV})
    def _cmd_look_hide(self, m: dict, now: float) -> object:
        """Hide a look from the picker (`hidden`, true unless said), or show it
        again. Any look, stored or block: hidden is not removed -- it still
        plays for a cue or a routine that names it, and auto mode skips it."""
        name, base = m["look"], m["base_rev"]
        hidden = m.get("hidden") is not False
        replaced_by, note = m.get("replaced_by"), m.get("note")
        event_dir, known = self.event_dir, tuple(self.by_name)
        return self._look_edit(
            f"{'hiding' if hidden else 'showing'} look {name}",
            lambda: lookstore.hide(event_dir, name, hidden, base, known,
                                   replaced_by, note),
            (f"hid look {name!r} from the picker" if hidden
             else f"look {name!r} is back in the picker"),
            data={"name": name, "hidden": hidden})

    @command("looks_reload", tier=CONFIGURE)
    def _cmd_looks_reload(self, m: dict, now: float) -> object:
        """Read both look files again now -- after an edit by hand, or by MCP.
        A file that does not load is said, and the library that is running
        runs on."""
        return self._look_edit("reading the looks again", lambda: None,
                               "looks read again from the event folder")

    def _install_looks(self, entries: list, rev: Optional[str],
                       seen: Optional[tuple] = None, *,
                       renamed: Optional[tuple[str, str]] = None) -> dict:
        """Make a freshly read look library the one that is running.

        On the output thread, at a frame boundary, like every other mutation.
        Everything that holds a look BY NAME is brought along or let go:

          * the movement look on stage stays up if it still exists (under its
            new name, after a rename); if it is gone, the first movement look
            takes over and a notice says so
          * a color or level slot, a stacked move, tuning and a modulator
            naming a look that is gone are dropped -- and tuning on a look
            whose block or arguments CHANGED is dropped too, since it was
            dialled in over the old authored values (a rename alone keeps it)
          * after a rename, the presets and the cue list follow the name --
            in memory first; presets.json is written LAST, because it is the
            one step here that can fail, and by then the library is installed
            whatever becomes of it
          * the show folder's programs were built from the old library, so
            they are built again; what is playing plays on until its
            replacement lands (`TrackPlayer.refresh`)

        Everything the 10 Hz snapshot walks is REBOUND, never edited in place.
        """
        current = self.setlist.current()
        on_stage = current.name if current is not None else None
        moved = {"cues": 0, "presets": 0}
        before = dict(self.by_name)
        if renamed is not None and renamed[0] in before:
            # What it was, under what it is called now, to tell a change of
            # name from a change of arguments below.
            before[renamed[1]] = before[renamed[0]]
        if renamed is not None:
            old, new = renamed
            swap = lambda n: new if n == old else n            # noqa: E731
            on_stage = swap(on_stage)
            self.slots = {slot: {g: swap(n) for g, n in groups.items()}
                          for slot, groups in self.slots.items()}
            self.movement_extra = [swap(n) for n in self.movement_extra]
            self.look_params = {swap(k): v for k, v in self.look_params.items()}
            self.modulators.rename(old, new)
            presets = [lookstore.renamed(p, old, new) for p in self.presets]
            moved["presets"] = sum(a != b for a, b in zip(presets, self.presets))
            if moved["presets"]:
                self.presets = presets              # written last, below
            if self.cues is not None:
                cues = [replace(c, **lookstore.renamed(
                            {"movement": c.movement, "color": c.color,
                             "level": c.level, "params": c.params}, old, new))
                        for c in self.cues.cues]
                # (cues.json itself was rewritten with the look, on the worker)
                moved["cues"] = sum(a != b for a, b in zip(cues, self.cues.cues))
                self.cues.cues = cues

        setlist = (libmod.setlist_for(entries) if entries else default_setlist())
        by_name = {e.name: e for e in entries}
        if on_stage in {look.name for look in setlist.looks}:
            setlist.select(on_stage)
        else:
            fallback = next((e.name for e in entries
                             if e.is_movement and not e.retired), None)
            if fallback is not None:
                setlist.select(fallback)
            if on_stage is not None and setlist.current() is not None:
                self.note(f"{on_stage!r} was on stage and is no longer in the "
                          f"library: {setlist.current().name!r} is up instead")
        self.library, self.by_name, self.setlist = entries, by_name, setlist
        self.library_rev += 1
        self.director.setlist = setlist
        self.looks_rev = rev
        self.looks_problem = None
        if seen is not None:
            # What this load read, so the watcher does not read it again.
            self.look_watcher.seen = seen

        self.slots = {slot: {g: n for g, n in groups.items() if n in by_name}
                      for slot, groups in self.slots.items()}
        self.movement_extra = [n for n in self.movement_extra
                               if n in by_name and by_name[n].is_movement]
        tunable = {e.name: e for e in entries if e.is_parametric}
        changed = {name for name, e in tunable.items()
                   if name in before and (before[name].block, before[name].args)
                   != (e.block, e.args)}
        self.look_params = {k: v for k, v in self.look_params.items()
                            if k in tunable and k not in changed}
        self.modulators.keep(lambda mod: not mod.look or (
            mod.look in tunable and parammod.find(
                blocksmod.PARAMS.get(tunable[mod.look].block or "", ()),
                mod.param) is not None))
        self._recompose()
        if self.player is not None:
            self.player.refresh()
            if self.show_library is not None:
                self.player.compile_idle(self.show_library)
            self._compile_pads()
            self._rematch_decks()
        if moved["presets"]:
            try:
                save_presets(self.event_dir, self.presets)
            except OSError as exc:
                self.note(f"presets.json could not be written ({exc}): the "
                          f"presets follow the rename here, and are written "
                          f"with the next preset that is saved")
        return moved

    def _public_looks(self) -> dict:
        """Which look files the library was read from. The library itself is
        not in the snapshot: see `looks_frame`."""
        return {
            # Which parametric_looks.json the library was read from. A
            # page that lists the library in full (Studio's Looks, over
            # /api/looks) reads it again when this moves, rather than polling.
            "looks_rev": self.looks_rev or "",
        }

    def looks_frame(self) -> dict:
        """The look library as the console offers it: a frame of its own,
        sent to a console when it connects and to every console when the
        library changes (`library_rev`), never in the 10 Hz snapshot.

        It was 86% of the snapshot -- some 50 kB of a 59 kB state, sent ten
        times a second to every phone in the room to say something that
        changes when someone edits a look. The snapshot's size is what decides
        how long a slow link takes to fall behind (`SEND_DEADLINE_S`).

        Built on the caller's thread from references the output thread only
        rebinds. The rev is read FIRST: the install bumps it after it rebinds
        the library, so the library read after it is that rev's or a newer
        one. Read the other way round, a frame could carry the old library
        under the new rev, and the broadcast thread would never send the new
        one -- every console stuck on a list nobody has.
        """
        rev = self.library_rev
        by_name, setlist = self.by_name, self.setlist
        # `kind` and `slot` let the UI put each look on the tab that owns it
        # and group within that -- a flat list of 200 is exactly why only a
        # handful got used. `step_of` files a chase's own steps under the
        # chase instead of beside it.
        # `cued` warns that this movement look drives the dimmer itself --
        # it travels dark. Worth saying on screen: an operator who picks one
        # and sees the rig start blinking should know that is the routine
        # and not a fault, and that it will fight a level chase for control.
        # `block` names the block behind a parametric look, which is what
        # lets the UI look its arguments up in the generated block table and
        # render a control panel for a look it has never heard of. Absent on
        # every ported look, which is the honest answer: a table of DMX has
        # nothing to tune.
        # `retired` hides an entry the operator has something better for.
        # Hidden, never removed -- looks.json is a generated artifact whose
        # round-trip proof depends on every entry staying in it, and going
        # back to the original should be one toggle away.
        looks = [{"name": l.name, "manual_only": l.manual_only,
                  "kind": by_name[l.name].kind if l.name in by_name else "look",
                  "slot": by_name[l.name].slot if l.name in by_name else "movement",
                  "cued": by_name[l.name].is_cued if l.name in by_name else False,
                  "groups": list(by_name[l.name].groups) if l.name in by_name else [],
                  "block": (by_name[l.name].block
                            if l.name in by_name else None),
                  "retired": (by_name[l.name].retired
                              if l.name in by_name else False),
                  "replaced_by": (by_name[l.name].replaced_by
                                  if l.name in by_name else None),
                  "args": (dict(by_name[l.name].args)
                           if l.name in by_name else {}),
                  "step_of": by_name[l.name].step_of if l.name in by_name else None}
                 for l in setlist.looks]
        return {"type": "looks", "rev": rev, "looks": looks}
